"""Render benchmark results as docs/BENCHMARKS.md.

    python benchmarks/render.py all_functions.jsonl real_world.json > docs/BENCHMARKS.md
"""

import collections
import json
import platform
import sys

import networkx as nx


NAMES = {
    "dag": "DAGs", "smallworld": "small world", "smetric": "s-metric", "wiener": "Wiener index",
    "lowest_common_ancestors": "lowest common ancestors", "d_separation": "d-separation",
    "non_randomness": "non-randomness", "graph_hashing": "graph hashing",
    "mis": "maximal independent set", "richclub": "rich club", "structuralholes": "structural holes",
}


def area(name):
    """The NetworkX sub-package a function lives in (its section here)."""
    d = nx.utils.backends._registered_algorithms.get(name)
    if d is None:
        return "other"
    parts = d.orig_func.__module__.split(".")
    if parts[1] == "algorithms" and len(parts) > 2:
        sub = parts[2]
        return NAMES.get(sub, sub.replace("_", " "))
    if parts[1] == "generators":
        return "generators"
    if parts[1] in ("readwrite", "convert", "convert_matrix", "drawing", "relabel"):
        return "reading, writing and conversion"
    if parts[1] == "linalg":
        return "linear algebra"
    return NAMES.get(parts[1], parts[1].replace("_", " "))


def secs(t):
    if t >= 100:
        return f"{t:.0f} s"
    if t >= 1:
        return f"{t:.2f} s"
    if t >= 0.01:
        return f"{t:.3f} s"
    if t >= 0.0001:
        return f"{t * 1000:.2f} ms"
    return f"{t * 1e6:.0f} µs"


def speed(a, b):
    x = a / b
    if x >= 10:
        return f"{x:,.0f}x"
    return f"{x:.1f}x" if x >= 0.1 else f"{x:.2f}x"


FAMILY = {
    "graph": "scale-free", "digraph": "random directed", "dag": "random DAG", "tree": "random tree",
    "bipartite": "random bipartite", "grid": "2D grid", "multigraph": "scale-free multigraph",
    "multidigraph": "random directed multigraph", "tournament": "random tournament",
    "complete": "complete", "complete_digraph": "complete directed",
}


def size(r):
    if r.get("edges") is not None:
        return f"{FAMILY.get(r['family'], r['family'])}, {r['n']:,} nodes, {r['edges']:,} edges"
    return f"n = {r['n']:,}"


def main():
    funcs = [json.loads(l) for l in open(sys.argv[1]) if l.strip()]
    pipes = json.load(open(sys.argv[2])) if len(sys.argv) > 2 else []
    ok = [r for r in funcs if r.get("status") == "ok"]
    out = []
    w = out.append
    w("# Benchmarks")
    w("")
    w("<!-- Generated by benchmarks/render.py from benchmarks/all_functions.py and benchmarks/real_world.py. -->")
    w("")
    w(f"Measured on a {platform.machine()} Linux machine with 4 cores, Python "
      f"{platform.python_version()}, NetworkX {nx.__version__}. rustnx's \"first call\" includes converting "
      "the NetworkX graph; \"repeat call\" reuses the conversion NetworkX caches on the graph. Every result was "
      "checked against NetworkX's: *same* means identical output (values and order), *close* means equal "
      "within 1e-9 relative (the functions that use fast floats by default).")
    w("")
    if pipes:
        w("## Real-world pipelines")
        w("")
        w("Each pipeline runs its steps once, as an analysis script would, on a "
          "[SNAP](https://snap.stanford.edu/data/) dataset (`python benchmarks/real_world.py`). rustnx's first "
          "step includes converting the graph.")
        w("")
        w("| Pipeline | Graph | NetworkX | rustnx | Speedup |")
        w("|---|---|---|---|---|")
        for p in pipes:
            kind = "directed" if p["directed"] else "undirected"
            w(f"| {p['pipeline']} | {p['nodes']:,} nodes, {p['edges']:,} edges, {kind} | "
              f"{secs(p['networkx_total'])} | {secs(p['rustnx_total'])} | **{speed(p['networkx_total'], p['rustnx_total'])}** |")
        w("")
        for p in pipes:
            w(f"### {p['pipeline']}")
            w("")
            w(f"`{p['dataset']}`: {p['nodes']:,} nodes, {p['edges']:,} edges.")
            w("")
            w("| Step | NetworkX | rustnx | Speedup | Result |")
            w("|---|---|---|---|---|")
            for s in p["steps"]:
                w(f"| `{s['step']}` | {secs(s['networkx'])} | {secs(s['rustnx'])} | {speed(s['networkx'], s['rustnx'])} | {s['match']} |")
            w(f"| **total** | **{secs(p['networkx_total'])}** | **{secs(p['rustnx_total'])}** | "
              f"**{speed(p['networkx_total'], p['rustnx_total'])}** | |")
            w("")
    w("## Every function")
    w("")
    w("`python benchmarks/all_functions.py` times each function rustnx implements. It grows the input (a "
      "scale-free graph, or the first graph family the function accepts) until NetworkX takes about half a "
      "second, or to 262,144 nodes, and times both on that input.")
    w("")
    speeds = sorted(r["nx"] / r["warm"] for r in ok)
    if speeds:
        med = speeds[len(speeds) // 2]
        faster = sum(s > 1.1 for s in speeds)
        slower = sum(s < 1 for s in speeds)
        w(f"Of {len(ok)} functions timed, {faster} are faster with rustnx on a repeat call "
          f"(median speedup {med:.1f}x) and {slower} are slower. Those are queries and checks NetworkX "
          "answers in microseconds (one cycle, `is_eulerian` on a graph that isn't), where NetworkX's "
          "dispatch overhead is most of rustnx's time, and functions whose time goes into building "
          "Python results (labeled edge streams, tiny generated graphs).")
        w("")
    match = collections.Counter(r.get("match") for r in ok)
    w(f"Results: {match.get('same', 0)} identical, {match.get('close', 0)} within 1e-9, "
      f"{match.get('DIFFERENT', 0)} different.")
    w("")
    groups = collections.defaultdict(list)
    for r in ok:
        groups[area(r["name"])].append(r)
    for g in sorted(groups, key=str.lower):
        w(f"### {g[0].upper() + g[1:]}")
        w("")
        w("| Function | Input | NetworkX | rustnx, first call | rustnx, repeat | Speedup | Result |")
        w("|---|---|---|---|---|---|---|")
        for r in sorted(groups[g], key=lambda r: r["name"]):
            w(f"| `{r['name']}` | {size(r)} | {secs(r['nx'])} | {secs(r['cold'])} | {secs(r['warm'])} | "
              f"{speed(r['nx'], r['warm'])} | {r['match']} |")
        w("")
    rest = [r for r in funcs if r.get("status") != "ok"]
    if rest:
        w("### Not timed")
        w("")
        w("| Function | Why |")
        w("|---|---|")
        for r in sorted(rest, key=lambda r: r["name"]):
            why = {"declined": "rustnx hands these inputs to NetworkX", "no-inputs": "no generated input fits",
                   "timeout": "NetworkX too slow at the smallest size"}.get(r["status"], r["status"])
            w(f"| `{r['name']}` | {why} |")
        w("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
